import {
  Color,
  Group,
  Matrix4,
  Mesh,
  MeshBasicMaterial,
  MeshPhysicalMaterial,
  MeshStandardMaterial,
  SphereGeometry,
  Vector3,
  type Material,
  type Object3D,
  type Shape,
} from "three";
import { GLTFLoader } from "three/addons/loaders/GLTFLoader.js";
import { THEME } from "@/theme/theme";
import {
  CHARACTER_LOGOS,
  CHARACTER_RIG,
  type LogoAnchor,
} from "./characterRig.generated";
import { createLogoGeometry } from "./logo";
import { modelUrl, type ModelTier } from "../quality/ModelDetail";

/**
 * Pivots the animation system drives. The model faces +Z; +X is its left.
 *
 *   root ─ squash ─┬─ body (hips) ─┬─ head (neck): hood + void face
 *                  │               ├─ arm (shoulder) ─ forearm (elbow): sleeve, cuff, hand
 *                  │               └─ torso, backpack, straps, chest + pack logos
 *                  └─ leg (hip) ─ shin (knee) ─ foot (ankle): sneaker
 */
export interface CharacterRig {
  root: Group;
  squash: Group;
  body: Group;
  head: Group;
  leftArm: Group;
  rightArm: Group;
  leftForearm: Group;
  rightForearm: Group;
  leftLeg: Group;
  rightLeg: Group;
  leftShin: Group;
  rightShin: Group;
  leftFoot: Group;
  rightFoot: Group;
  /** Rest heights of the body and leg pivots (animation offsets add to these). */
  bodyRestY: number;
  legRestY: number;
}

/** Loads the sculpted model generated by scripts/character/generate_character.py. */
export async function loadCharacterModel(
  tier: ModelTier,
  signal?: AbortSignal,
): Promise<Object3D> {
  const response = await fetch(modelUrl(tier), { signal });
  if (!response.ok)
    throw new Error(`Character model request failed (${response.status})`);
  const buffer = await response.arrayBuffer();
  const gltf = await new GLTFLoader().parseAsync(buffer, "");
  return gltf.scene;
}

const v3 = (a: readonly number[]) => new Vector3(a[0], a[1], a[2]);

/**
 * Wraps the generated meshes into an animation rig and assigns materials.
 * Albedo and ambient occlusion are baked into vertex colours, so materials
 * only define the surface response; neon-green parts are unlit emissives.
 */
export class Character {
  readonly rig: CharacterRig;

  constructor(model: Object3D, logoShapes: Shape[] | null) {
    const materials = createMaterials();
    const take = (name: string, material: Material): Mesh => {
      const mesh = model.getObjectByName(name);
      if (!(mesh instanceof Mesh))
        throw new Error(`Character model is missing "${name}"`);
      mesh.removeFromParent();
      mesh.position.set(0, 0, 0);
      mesh.rotation.set(0, 0, 0);
      mesh.scale.set(1, 1, 1);
      mesh.material = material;
      return mesh;
    };
    /** A pivot group placed at `world`, expressed relative to its parent's pivot. */
    const pivot = (parent: Group, parentWorld: Vector3, world: Vector3) => {
      const group = new Group();
      group.position.copy(world).sub(parentWorld);
      parent.add(group);
      return group;
    };
    const logo = (
      parent: Group,
      parentWorld: Vector3,
      anchor: LogoAnchor,
      name: string,
    ) => {
      if (!logoShapes) return;
      parent.add(
        createEmblem(logoShapes, anchor, parentWorld, materials.green, name),
      );
    };

    const origin = new Vector3();
    const hip = v3(CHARACTER_RIG.hip);
    const neck = v3(CHARACTER_RIG.neck);

    const root = new Group();
    root.name = "player";
    const squash = new Group();
    root.add(squash);

    const body = pivot(squash, origin, hip);
    body.add(
      take("torso", materials.fabric),
      take("backpack", materials.pack),
      take("straps", materials.strap),
      take("packPiping", materials.green),
    );
    logo(body, hip, CHARACTER_LOGOS.logoChest, "logo-chest");
    logo(body, hip, CHARACTER_LOGOS.logoBack, "logo-backpack");

    // The face is a void: a pure black head recessed in the hood's cavity.
    const head = pivot(body, hip, neck);
    head.add(take("hood", materials.fabric));
    const face = new Mesh(new SphereGeometry(1, 32, 24), materials.void);
    face.scale.copy(v3(CHARACTER_RIG.headRadii));
    face.position.copy(v3(CHARACTER_RIG.headCenter)).sub(neck);
    head.add(face);

    const createArm = (tag: "L" | "R") => {
      const shoulder = v3(
        tag === "L" ? CHARACTER_RIG.shoulderL : CHARACTER_RIG.shoulderR,
      );
      const elbow = v3(
        tag === "L" ? CHARACTER_RIG.elbowL : CHARACTER_RIG.elbowR,
      );
      const arm = pivot(body, hip, shoulder);
      arm.add(take(`upperArm${tag}`, materials.fabric));
      logo(
        arm,
        shoulder,
        tag === "L" ? CHARACTER_LOGOS.logoSleeveL : CHARACTER_LOGOS.logoSleeveR,
        `logo-sleeve-${tag}`,
      );
      const forearm = pivot(arm, shoulder, elbow);
      forearm.add(
        take(`forearm${tag}`, materials.fabric),
        take(`cuffBands${tag}`, materials.green),
        take(`hand${tag}`, materials.glove),
      );
      return { arm, forearm };
    };

    const createLeg = (tag: "L" | "R") => {
      const hipJoint = v3(
        tag === "L" ? CHARACTER_RIG.legL : CHARACTER_RIG.legR,
      );
      const knee = v3(tag === "L" ? CHARACTER_RIG.kneeL : CHARACTER_RIG.kneeR);
      const ankle = v3(
        tag === "L" ? CHARACTER_RIG.ankleL : CHARACTER_RIG.ankleR,
      );
      const leg = pivot(squash, origin, hipJoint);
      leg.add(take(`thigh${tag}`, materials.fabric));
      const shin = pivot(leg, hipJoint, knee);
      shin.add(take(`shin${tag}`, materials.fabric));
      const foot = pivot(shin, knee, ankle);
      foot.add(
        take(`shoe${tag}`, materials.shoe),
        take(`sole${tag}`, materials.sole),
        take(`shoeGlow${tag}`, materials.green),
      );
      return { leg, shin, foot };
    };

    const left = createArm("L");
    const right = createArm("R");
    const leftLeg = createLeg("L");
    const rightLeg = createLeg("R");

    this.rig = {
      root,
      squash,
      body,
      head,
      leftArm: left.arm,
      rightArm: right.arm,
      leftForearm: left.forearm,
      rightForearm: right.forearm,
      leftLeg: leftLeg.leg,
      rightLeg: rightLeg.leg,
      leftShin: leftLeg.shin,
      rightShin: rightLeg.shin,
      leftFoot: leftLeg.foot,
      rightFoot: rightLeg.foot,
      bodyRestY: hip.y,
      legRestY: CHARACTER_RIG.legL[1],
    };
  }
}

/** Extrudes the supplied SVG logo and lays it on a surface anchor. */
export function createEmblem(
  shapes: Shape[],
  anchor: LogoAnchor,
  parentWorld: Vector3,
  material: Material,
  name: string,
): Mesh {
  const mesh = new Mesh(
    createLogoGeometry(shapes, anchor.height, 0.004),
    material,
  );
  // Orthonormal basis: +Z along the surface normal, +Y kept as upright as possible.
  const z = v3(anchor.normal).normalize();
  const up = Math.abs(z.y) > 0.9 ? new Vector3(0, 0, 1) : new Vector3(0, 1, 0);
  const x = new Vector3().crossVectors(up, z).normalize();
  const y = new Vector3().crossVectors(z, x);
  mesh.quaternion.setFromRotationMatrix(new Matrix4().makeBasis(x, y, z));
  mesh.position.copy(v3(anchor.position)).sub(parentWorld);
  mesh.name = name;
  return mesh;
}

function createMaterials() {
  // Owned by the scene graph; released by disposeObject() on teardown.
  const fabricSheen = new Color("#7a8396");
  return {
    fabric: new MeshPhysicalMaterial({
      vertexColors: true,
      roughness: 0.82,
      sheen: 0.9,
      sheenColor: fabricSheen,
      sheenRoughness: 0.55,
    }),
    glove: new MeshStandardMaterial({ vertexColors: true, roughness: 0.6 }),
    shoe: new MeshStandardMaterial({ vertexColors: true, roughness: 0.45 }),
    sole: new MeshStandardMaterial({ vertexColors: true, roughness: 0.6 }),
    pack: new MeshStandardMaterial({
      vertexColors: true,
      roughness: 0.55,
      metalness: 0.1,
    }),
    strap: new MeshStandardMaterial({ vertexColors: true, roughness: 0.8 }),
    green: new MeshBasicMaterial({
      color: new Color(THEME.green),
      toneMapped: false,
    }),
    void: new MeshBasicMaterial({ color: 0x000000 }),
  };
}
